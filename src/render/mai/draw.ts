/** 单条成绩（内部模型，字段口径对齐 PlayedResult）。 */
export interface MaiB50Row {
  /** maimai song_id：standard 为曲目 id，dx 为 id + 10000。 */
  songId: number;
  title: string;
  levelIndex: number;
  type: 'SD' | 'DX';
  rating: number;
  achievements: number;
  /** 小写评价（sss/sp/aa/...），null 时不画评价图标。 */
  rate: string | null;
  /** fc 类型（fc/fcp/ap/app）。 */
  fc: string | null;
  /** fs 类型（fs/fsp/fsd/fsdp/sync）。 */
  fs: string | null;
  dxScore: number | null;
  levelValue: number | null;
}

export interface MaiB50Trophy {
  name: string;
  /** TrophyColor：Normal / Bronze / Silver / Gold / Rainbow */
  color: string;
}

/** 头部数据（Player）。 */
export interface MaiB50Player {
  name: string;
  rating: number;
  courseRank: number;
  classRank: number;
  trophy: MaiB50Trophy | null;
}

export interface MaiB50Model {
  player: MaiB50Player;
  sd: MaiB50Row[];
  dx: MaiB50Row[];
  sdTotal: number;
  dxTotal: number;
}

export interface RenderB50Options {
  theme?: MaiTheme;
  assets?: MaiAssets;
  songData?: MaiSongData;
  /** 页脚 “Data from {service}”。 */
  serviceLabel?: string;
  /** 页脚 “Generated by {botName} BOT”。 */
  botName?: string;
}

/** DX 星数（core/utils/calc.py dx_score，入参为百分比）。 */
export function dxStarOf(percent: number): number {
  if (percent < 85) return 0;
  if (percent < 90) return 1;
  if (percent < 93) return 2;
  if (percent < 95) return 3;
  if (percent < 97) return 4;
  return 5;
}

const BLACK = 'rgb(0,0,0)';

/**
 * 页脚文案（best50.py:197-209 的 `Designed by …` 必须保留署名）。
 * 与上游唯一差异：`Data from {service}` 换成 RankHub（数据源不同），文案由调用方覆盖。
 */
export function buildFooterText(serviceLabel: string, botName: string): string {
  return (
    `Designed by Yuri-YuzuChaN & BlueDeer233. Data from ${serviceLabel}. ` +
    `Generated by ${botName} BOT`
  );
}

function color(c: readonly string[], index: number, fallback = 'rgb(255,255,255)'): string {
  return c[index] ?? c[0] ?? fallback;
}

/** 按目标尺寸贴图（等价 PIL alpha_composite + resize）。 */
function paste(
  ctx: SKRSContext2D,
  assets: MaiAssets,
  rel: string,
  x: number,
  y: number,
  w: number,
  h: number,
): void {
  ctx.drawImage(assets.scaledImage(rel, w, h), x, y);
}

/** 贴原尺寸图（不缩放）。 */
function pasteRaw(
  ctx: SKRSContext2D,
  assets: MaiAssets,
  rel: string,
  x: number,
  y: number,
): void {
  const img = assets.image(rel);
  ctx.drawImage(img, x, y);
}

/**
 * 头部（best50.py:119-209）。
 * 顺序必须一致：后画的覆盖先画的（logo → 名牌 → 头像 → rating 牌 → 数字 → 名称 → 段位/Class → 称号条 → 文字）。
 */
function drawHeader(
  ctx: SKRSContext2D,
  assets: MaiAssets,
  model: MaiB50Model,
  theme: MaiTheme,
  serviceLabel: string,
  botName: string,
): void {
  const { player } = model;

  // best50.py:108,120 —— logo 249×120 @ (14,60)
  paste(ctx, assets, `pic/${theme}/logo.png`, HEADER.logo.x, HEADER.logo.y, HEADER.logo.w, HEADER.logo.h);

  // best50.py:123-129 —— 名牌 800×130 @ (300,60)（默认 UI_Plate_550101.png ⇔ plate/0.png）
  paste(ctx, assets, 'plate/0.png', HEADER.plate.x, HEADER.plate.y, HEADER.plate.w, HEADER.plate.h);

  // best50.py:131-140 —— 头像 120×120 @ (305,65)
  paste(ctx, assets, 'pic/UI_Icon_509506.png', HEADER.icon.x, HEADER.icon.y, HEADER.icon.w, HEADER.icon.h);

  // best50.py:142-165 —— DX Rating 牌 + （CIRCLE 主题 14000+ 的）星级
  const rating = Math.trunc(player.rating);
  let ratingNum: { x: number; y: number; gap: number; w: number; h: number } = HEADER.ratingNum;
  if (theme === 'circle' && rating >= 14000) {
    ratingNum = HEADER.ratingNumCircle;
    paste(
      ctx,
      assets,
      `pic/${theme}/${findRaStarPic(rating)}`,
      HEADER.dxRatingStarCircle.x,
      HEADER.dxRatingStarCircle.y,
      HEADER.dxRatingStarCircle.w,
      HEADER.dxRatingStarCircle.h,
    );
    paste(
      ctx,
      assets,
      `pic/${theme}/${findRaPic(rating)}`,
      HEADER.dxRatingPlateCircle.x,
      HEADER.dxRatingPlateCircle.y,
      HEADER.dxRatingPlateCircle.w,
      HEADER.dxRatingPlateCircle.h,
    );
  } else {
    paste(
      ctx,
      assets,
      `pic/${theme}/${findRaPic(rating)}`,
      HEADER.dxRatingPlate.x,
      HEADER.dxRatingPlate.y,
      HEADER.dxRatingPlate.w,
      HEADER.dxRatingPlate.h,
    );
  }

  // best50.py:167-171 —— rating 五位数字精灵（UI_NUM_Drating_<d>.png）
  const digits = String(rating).padStart(5, '0');
  for (let n = 0; n < digits.length; n += 1) {
    const d = digits[n]!;
    paste(
      ctx,
      assets,
      `pic/UI_NUM_Drating_${d}.png`,
      ratingNum.x + ratingNum.gap * n,
      ratingNum.y,
      ratingNum.w,
      ratingNum.h,
    );
  }

  // best50.py:173 —— 名称条底图 pic/Name.png（原尺寸 272×42）@ (435,115)
  pasteRaw(ctx, assets, 'pic/Name.png', HEADER.nameImage.x, HEADER.nameImage.y);

  // best50.py:174 —— 段位牌 80×32 @ (625,120)
  paste(
    ctx,
    assets,
    `pic/UI_DNM_DaniPlate_${daniPlateNum(player.courseRank)}.png`,
    HEADER.daniPlate.x,
    HEADER.daniPlate.y,
    HEADER.daniPlate.w,
    HEADER.daniPlate.h,
  );

  // best50.py:175 —— Class 牌 90×54 @ (620,60)
  paste(
    ctx,
    assets,
    `pic/UI_FBR_Class_${String(player.classRank).padStart(2, '0')}.png`,
    HEADER.classPlate.x,
    HEADER.classPlate.y,
    HEADER.classPlate.w,
    HEADER.classPlate.h,
  );

  // best50.py:177-194 —— 称号条（有称号则显示称号名，否则显示 B35 + B15 = rating）
  let trophyTitle: string;
  let trophyFont: FontFamily;
  if (player.trophy) {
    trophyTitle = player.trophy.name;
    paste(
      ctx,
      assets,
      `shougou/UI_CMN_Shougou_${player.trophy.color}.png`,
      HEADER.trophyBar.x,
      HEADER.trophyBar.y,
      HEADER.trophyBar.w,
      HEADER.trophyBar.h,
    );
    trophyFont = 'SIYUAN';
  } else {
    trophyTitle = `B35: ${model.sdTotal} + B15: ${model.dxTotal} = ${rating}`;
    paste(
      ctx,
      assets,
      'shougou/UI_CMN_Shougou_Rainbow.png',
      HEADER.trophyBar.x,
      HEADER.trophyBar.y,
      HEADER.trophyBar.w,
      HEADER.trophyBar.h,
    );
    trophyFont = 'TBFONT';
  }
  drawText(ctx, {
    family: trophyFont,
    size: HEADER.trophyText.size,
    x: HEADER.trophyText.x,
    y: HEADER.trophyText.y,
    text: trophyTitle,
    color: BLACK,
    anchor: 'mm',
  });

  // best50.py:196 —— 玩家名 SIYUAN 20 @ (445,135) 左中
  drawText(ctx, {
    family: 'SIYUAN',
    size: HEADER.nameText.size,
    x: HEADER.nameText.x,
    y: HEADER.nameText.y,
    text: player.name,
    color: BLACK,
    anchor: 'lm',
  });

  // best50.py:197-209 —— 页脚（署名保留上游原样）
  drawText(ctx, {
    family: 'SIYUAN',
    size: HEADER.footer.size,
    x: HEADER.footer.x,
    y: HEADER.footer.y,
    text: buildFooterText(serviceLabel, botName),
    color: THEME_COLOR[theme],
    anchor: 'mm',
    strokeWidth: HEADER.footer.stroke,
    strokeFill: 'rgb(255,255,255)',
  });
}

/** 单张成绩卡（base.py:104-189）。 */
function drawScoreCard(
  ctx: SKRSContext2D,
  assets: MaiAssets,
  songData: MaiSongData,
  theme: MaiTheme,
  row: MaiB50Row,
  x: number,
  y: number,
): void {
  const diff = row.levelIndex;
  const diffName = DIFF_NAMES[diff];
  const diffTextColor = color(DIFF_TEXT_COLORS, diff);
  const idTextColor = color(ID_TEXT_COLORS, diff);

  // base.py:122 —— 难度底图（原尺寸 264×109）
  if (diffName) {
    pasteRaw(ctx, assets, `pic/b50_score_${diffName}.png`, x, y);
  }

  // base.py:109-110 —— 曲绘 75×75（缺图回落 0.png）
  ctx.drawImage(
    assets.scaledCover(row.songId, CARD.cover.size, CARD.cover.size),
    x + CARD.cover.dx,
    y + CARD.cover.dy,
  );

  // base.py:110 —— STD/DX 标 37×14
  paste(
    ctx,
    assets,
    `pic/${row.type}.png`,
    x + CARD.type.dx,
    y + CARD.type.dy,
    CARD.type.w,
    CARD.type.h,
  );

  // base.py:111-121 —— 评价图标 63×28（rate 为 null 时不画）
  if (row.rate) {
    const key = RANK_MAP[row.rate.toLowerCase()];
    if (key) {
      paste(
        ctx,
        assets,
        `pic/${theme}/UI_TTR_Rank_${key}.png`,
        x + CARD.rate.dx,
        y + CARD.rate.dy,
        CARD.rate.w,
        CARD.rate.h,
      );
    }
  }

  // base.py:126-130 —— FC 标
  if (row.fc) {
    const key = COMBO_MAP[row.fc.toLowerCase()];
    if (key) {
      paste(
        ctx,
        assets,
        `pic/UI_MSS_MBase_Icon_${key}.png`,
        x + CARD.fc.dx,
        y + CARD.fc.dy,
        CARD.fc.size,
        CARD.fc.size,
      );
    }
  }

  // base.py:131-135 —— FS 标
  if (row.fs) {
    const key = SYNC_MAP[row.fs.toLowerCase()];
    if (key) {
      paste(
        ctx,
        assets,
        `pic/UI_MSS_MBase_Icon_${key}.png`,
        x + CARD.fs.dx,
        y + CARD.fs.dy,
        CARD.fs.size,
        CARD.fs.size,
      );
    }
  }

  // base.py:137-142 —— DX 星（dx_score / 满 DX 分）
  const maxDx = row.dxScore == null ? null : songData.maxDxScore(row.songId, diff);
  if (row.dxScore != null && maxDx != null && maxDx > 0) {
    const star = dxStarOf((row.dxScore / maxDx) * 100);
    if (star > 0) {
      paste(
        ctx,
        assets,
        `pic/UI_GAM_Gauge_DXScoreIcon_0${star}.png`,
        x + CARD.dxStar.dx,
        y + CARD.dxStar.dy,
        CARD.dxStar.w,
        CARD.dxStar.h,
      );
    }
  }

  // base.py:144-151 —— 曲目 ID（TBFONT 13 @ x+26,y+98 居中）
  drawText(ctx, {
    family: 'TBFONT',
    size: CARD.songId.size,
    x: x + CARD.songId.dx,
    y: y + CARD.songId.dy,
    text: String(row.songId),
    color: idTextColor,
    anchor: 'mm',
  });

  // base.py:153-163 —— 曲名 SIYUAN 14 @ x+93,y+14 左中（超宽截断）
  drawText(ctx, {
    family: 'SIYUAN',
    size: CARD.title.size,
    x: x + CARD.title.dx,
    y: y + CARD.title.dy,
    text: fitTitle(row.title, CARD.title.maxColumns, CARD.title.clipColumns),
    color: diffTextColor,
    anchor: 'lm',
  });

  // base.py:164-171 —— 达成率 TBFONT 30 @ x+93,y+38 左中
  drawText(ctx, {
    family: 'TBFONT',
    size: CARD.achievements.size,
    x: x + CARD.achievements.dx,
    y: y + CARD.achievements.dy,
    text: `${row.achievements.toFixed(4)}%`,
    color: diffTextColor,
    anchor: 'lm',
  });

  // base.py:172-179 —— DX 分 TBFONT 15 @ x+219,y+65 居中
  drawText(ctx, {
    family: 'TBFONT',
    size: CARD.dxScore.size,
    x: x + CARD.dxScore.dx,
    y: y + CARD.dxScore.dy,
    text: `${row.dxScore ?? 0}/${maxDx ?? '?'}`,
    color: diffTextColor,
    anchor: 'mm',
  });

  // base.py:181-189 —— 定数 → rating TBFONT 15 @ x+93,y+65 左中；缺定数显示 `? -> rating`
  const ds = row.levelValue ?? songData.levelValue(row.songId, diff);
  drawText(ctx, {
    family: 'TBFONT',
    size: CARD.levelValue.size,
    x: x + CARD.levelValue.dx,
    y: y + CARD.levelValue.dy,
    text: `${ds == null ? '?' : ds} -> ${row.rating}`,
    color: diffTextColor,
    anchor: 'lm',
  });
}

/** 成绩卡网格（base.py:95-107 + whiledraw 的调用点 best50.py:211-212）。 */
function drawScoreCards(
  ctx: SKRSContext2D,
  assets: MaiAssets,
  songData: MaiSongData,
  theme: MaiTheme,
  rows: MaiB50Row[],
  dx: boolean,
): void {
  const initialY = dx ? GRID.dxInitialY : GRID.sdInitialY;
  rows.forEach((row, num) => {
    const rowIndex = Math.floor(num / 5);
    const col = num % 5;
    const x = GRID.startX + col * GRID.dxStep;
    const y = initialY + rowIndex * GRID.gap;
    drawScoreCard(ctx, assets, songData, theme, row, x, y);
  });
}

/**
 * 收集本次渲染会用到的一切图片路径（供 preload）。
 * 必须是「绘制逻辑用到的全部路径」的超集，漏一个会在绘制时抛「资源未预载」。
 */
export function collectAssetPaths(model: MaiB50Model, theme: MaiTheme, assets?: MaiAssets): string[] {
  const { player } = model;
  const rating = Math.trunc(player.rating);
  const paths = new Set<string>([
    `pic/${theme}/b50.png`,
    `pic/${theme}/logo.png`,
    'plate/0.png',
    'pic/UI_Icon_509506.png',
    `pic/${theme}/${findRaPic(rating)}`,
    'pic/Name.png',
    `pic/UI_DNM_DaniPlate_${daniPlateNum(player.courseRank)}.png`,
    `pic/UI_FBR_Class_${String(player.classRank).padStart(2, '0')}.png`,
    'pic/SD.png',
    'pic/DX.png',
    'shougou/UI_CMN_Shougou_Rainbow.png',
  ]);

  for (let digit = 0; digit <= 9; digit += 1) paths.add(`pic/UI_NUM_Drating_${digit}.png`);
  for (let star = 1; star <= 5; star += 1) paths.add(`pic/UI_GAM_Gauge_DXScoreIcon_0${star}.png`);
  for (const name of DIFF_NAMES) paths.add(`pic/b50_score_${name}.png`);
  for (const rank of Object.values(RANK_MAP)) paths.add(`pic/${theme}/UI_TTR_Rank_${rank}.png`);
  for (const icon of Object.values(COMBO_MAP)) paths.add(`pic/UI_MSS_MBase_Icon_${icon}.png`);
  for (const icon of Object.values(SYNC_MAP)) paths.add(`pic/UI_MSS_MBase_Icon_${icon}.png`);
  if (player.trophy) paths.add(`shougou/UI_CMN_Shougou_${player.trophy.color}.png`);
  if (theme === 'circle' && rating >= 14000) {
    for (let num = 1; num <= 4; num += 1) paths.add(`pic/${theme}/UI_CMN_DXRating_Star_0${num}.png`);
  }

  // 曲绘：实际路径按「是否存在」回落 cover/0.png
  for (const row of [...model.sd, ...model.dx]) {
    paths.add(assets ? assets.coverRel(row.songId) : `cover/${((row.songId % 10000) + 10000) % 10000}.png`);
  }
  paths.add('cover/0.png');
  return [...paths];
}

/**
 * 画布池：复用整图 canvas（1400×1600 RGBA ≈ 9 MB）。
 *
 * 不复用的话，长跑进程每次渲染都新分配一块 9 MB 原生内存；@napi-rs/canvas 的
 * Canvas 是 napi 外部对象，V8 不感知其内存压力，GC 很懒 → RSS 会持续爬升
 * （实测 40 次渲染从 210 MB 涨到 657 MB）。复用后只有 PNG 编码缓冲是每次新建。
 */
const canvasPool = new Map<string, Canvas[]>();

function acquireCanvas(width: number, height: number): Canvas {
  const key = `${width}x${height}`;
  const free = canvasPool.get(key);
  const reused = free?.pop();
  if (reused) return reused;
  return createCanvas(width, height);
}

function releaseCanvas(canvas: Canvas): void {
  const key = `${canvas.width}x${canvas.height}`;
  const free = canvasPool.get(key) ?? [];
  if (free.length < 2) free.push(canvas);
  canvasPool.set(key, free);
}

/** 渲染整张 b50 PNG（返回 Buffer）。 */
export async function renderB50Png(model: MaiB50Model, options: RenderB50Options = {}): Promise<Buffer> {
  const theme = options.theme ?? 'prism_plus';
  const assets = options.assets ?? new MaiAssets();
  const songData = options.songData ?? loadSongData(assets.dir);

  // 第一步：把所有图片并行解码到缓存（@napi-rs/canvas 的像素解码是异步的）
  await assets.preload(collectAssetPaths(model, theme, assets));

  // 第二步：完全同步地按上游坐标逐层绘制
  const serviceLabel = options.serviceLabel ?? 'RankHub';
  const botName = options.botName ?? 'RankHub';

  const background = assets.themed(theme, 'b50.png');
  const canvas = acquireCanvas(background.width, background.height);
  const ctx = canvas.getContext('2d');
  // 复用画布时必须清空上一次的内容与状态
  ctx.reset();
  ctx.imageSmoothingEnabled = true;
  ctx.imageSmoothingQuality = 'high';
  ctx.drawImage(background, 0, 0);

  try {
    drawHeader(ctx, assets, model, theme, serviceLabel, botName);
    drawScoreCards(ctx, assets, songData, theme, model.sd, false);
    drawScoreCards(ctx, assets, songData, theme, model.dx, true);
    // 用异步 encode 而不是 toBuffer：实测 @napi-rs/canvas 0.1.100 的同步 toBuffer
    // 每次 PNG 编码会滞留 ~1.6 MB 原生内存（60 次编码 RSS 66→166 MB），
    // 异步 encode 前后 RSS 稳定（66 MB）。见 spike 报告「长跑内存」一节。
    return await canvas.encode('png');
  } finally {
    releaseCanvas(canvas);
  }
}
