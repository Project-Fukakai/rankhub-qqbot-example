/**
 * maimai b50 渲染器：契约 `Renderer.renderMaimaiB50` 的移植实现。
 *
 * 路线：纯 Node（@napi-rs/canvas）移植 maimaiDX 绘制，坐标逐像素照抄，
 * 不依赖 Python / Playwright。评估结论见 evidence/qqbot/render/maimai-spike.md。
 *
 * 数据映射：RankHub `GameBests` → 内部模型
 *   buckets: latest(15 条) → dx 区（B15，initial_y=1085）
 *            archive(35 条) → sd 区（B35，initial_y=235）
 *   totals:  由各条 rating 求和（B35 合计 / B15 合计），与 maimaiDX `sd_total/dx_total` 同义。
 *   定数/满 DX 分：vendor/mai/data.json（songId-levelIndex → level_value / notes.total*3）。
 */
