export interface MaimaiRendererOptions {
  /** 资源目录，默认 MAIMAIDX_STATIC 或 <cwd>/vendor/mai。 */
  assetsDir?: string;
  /** 主题，默认 prism_plus（与 maimaiDX 默认一致）。 */
  theme?: MaiTheme;
  /** 页脚 “Data from …”，默认 RankHub。 */
  serviceLabel?: string;
  /** 页脚 “Generated by … BOT”，默认 RankHub。 */
  botName?: string;
}

/** 契约里没有的头部字段（段位/Class/称号），可通过扩展字段传入；缺省用安全默认值。 */
export interface MaimaiB50RenderExtras {
  courseRank?: number;
  classRank?: number;
  trophy?: MaiB50Trophy | null;
  theme?: MaiTheme;
}

const DIFF_NAME_TO_INDEX: Record<string, number> = {
  basic: 0,
  advanced: 1,
  expert: 2,
  master: 3,
  remaster: 4,
  're:master': 4,
  re_master: 4,
};

/** 达成率 → 评价（core/utils/calc.py compute_rating 的 rate 段）。 */
export function rateOf(achievements: number): string {
  if (achievements < 50) return 'd';
  if (achievements < 60) return 'c';
  if (achievements < 70) return 'b';
  if (achievements < 75) return 'bb';
  if (achievements < 80) return 'bbb';
  if (achievements < 90) return 'a';
  if (achievements < 94) return 'aa';
  if (achievements < 97) return 'aaa';
  if (achievements < 98) return 's';
  if (achievements < 99) return 'sp';
  if (achievements < 99.5) return 'ss';
  if (achievements < 100) return 'ssp';
  if (achievements < 100.5) return 'sss';
  return 'sssp';
}

const BASE_RA_SPP = [7, 8, 9.6, 11.2, 12, 13.6, 15.2, 16.8, 20, 20.3, 20.8, 21.1, 21.6, 22.4];
const ACHIEVEMENT_THRESHOLDS = [50, 60, 70, 75, 80, 90, 94, 97, 98, 99, 99.5, 100, 100.5];

function baseRa(achievements: number): number {
  for (let i = 0; i < ACHIEVEMENT_THRESHOLDS.length; i += 1) {
    if (achievements < ACHIEVEMENT_THRESHOLDS[i]!) return BASE_RA_SPP[i]!;
  }
  return BASE_RA_SPP[BASE_RA_SPP.length - 1]!;
}

/** 由定数 + 达成率算单曲 rating（与上游 compute_rating 一致，向下取整）。 */
export function computeRating(levelValue: number, achievements: number): number {
  return Math.floor(levelValue * (Math.min(100.5, achievements) / 100) * baseRa(achievements));
}

function num(value: unknown): number | null {
  if (typeof value === 'number' && Number.isFinite(value)) return value;
  if (typeof value === 'string' && value.trim() !== '') {
    const parsed = Number(value);
    return Number.isFinite(parsed) ? parsed : null;
  }
  return null;
}

/** songId 归一：优先 native 里的原始数值，其次解析契约里的字符串。 */
export function normalizeSongId(score: GameScore): number | null {
  const native = (score.native ?? {}) as Record<string, unknown>;
  for (const key of ['song_id', 'songId', 'id', 'music_id', 'musicId']) {
    const value = num(native[key]);
    if (value != null) return value;
  }
  if (score.songId != null && /^\d+$/.test(String(score.songId).trim())) {
    return Number(String(score.songId).trim());
  }
  return null;
}

function normalizeLevelIndex(score: GameScore): number | null {
  const raw = score.levelIndex;
  if (typeof raw === 'number' && Number.isInteger(raw) && raw >= 0 && raw <= 4) return raw;
  const byName = DIFF_NAME_TO_INDEX[String(score.difficulty ?? '').trim().toLowerCase()];
  if (byName != null) return byName;
  const byNumber = num(raw ?? score.difficulty);
  if (byNumber != null && byNumber >= 0 && byNumber <= 4) return Math.trunc(byNumber);
  return null;
}

function normalizeType(score: GameScore, songId: number | null): 'SD' | 'DX' {
  const t = String(score.type ?? '').trim().toLowerCase();
  if (t === 'dx' || t === 'deluxe') return 'DX';
  if (t === 'standard' || t === 'sd' || t === 'std') return 'SD';
  return songId != null && songId >= 10000 ? 'DX' : 'SD';
}

function normalizeRate(score: GameScore, achievements: number): string | null {
  const raw = String(score.rank ?? '').trim().toLowerCase();
  if (raw) {
    const cleaned = raw.replace(/＋/g, '+').replace(/\s+/g, '');
    if (cleaned.endsWith('+')) return `${cleaned.slice(0, -1)}p`;
    if (cleaned !== '') return cleaned;
  }
  return rateOf(achievements);
}

function normalizeCombo(fc: string | null): string | null {
  if (!fc) return null;
  const raw = fc.trim().toLowerCase().replace(/＋/g, '+').replace(/\s+/g, '');
  if (!raw) return null;
  if (raw.endsWith('+')) return `${raw.slice(0, -1)}p`;
  return raw;
}

function normalizeSync(fs: string | null): string | null {
  if (!fs) return null;
  const raw = fs.trim().toLowerCase().replace(/＋/g, '+').replace(/\s+/g, '');
  if (!raw) return null;
  // maimaiDX 的 SYNC_MAP：fs / fsp / fsd / fsdp / sync；DX 谱的 FDX 也归到 FSD 图标
  if (raw === 'fdx') return 'fsd';
  if (raw === 'fdx+') return 'fsdp';
  if (raw.endsWith('+')) return `${raw.slice(0, -1)}p`;
  return raw;
}

function toRow(score: GameScore, songData: MaiSongData): MaiB50Row | null {
  const songId = normalizeSongId(score);
  const levelIndex = normalizeLevelIndex(score);
  if (songId == null || levelIndex == null) return null;

  const achievements = num(score.achievements) ?? 0;
  const levelValue = num(score.level) ?? songData.levelValue(songId, levelIndex);
  const rating = num(score.rating) ?? (levelValue != null ? computeRating(levelValue, achievements) : 0);
  const native = (score.native ?? {}) as Record<string, unknown>;

  return {
    songId,
    title: score.songName ?? songData.title(songId) ?? native.title?.toString() ?? `#${songId}`,
    levelIndex,
    type: normalizeType(score, songId),
    rating,
    achievements,
    rate: normalizeRate(score, achievements),
    fc: normalizeCombo(score.fc),
    fs: normalizeSync(score.fs),
    dxScore: num(score.dxScore),
    levelValue,
  };
}

/** 识别 latest（B15）/ archive（B35）两个 bucket；识别不了就按条目数兜底。 */
export function pickBuckets(
  input: MaimaiB50RenderInput,
): { sd: GameScore[]; dx: GameScore[] } {
  const buckets = input.buckets.filter((bucket) => bucket.items.length > 0);
  const describe = (bucket: { key: string; label?: string }): string =>
    `${bucket.key} ${bucket.label ?? ''}`;
  const dxBucket = buckets.find((bucket) => /latest|new|b15|dx/i.test(describe(bucket)));
  const sdBucket = buckets.find((bucket) => /archive|old|b35|sd|history/i.test(describe(bucket)));
  if (dxBucket && sdBucket) return { sd: sdBucket.items, dx: dxBucket.items };

  if (buckets.length >= 2) {
    // latest 一定比 archive 短（15 vs 35），用长度区分，避免依赖 bucket key 命名
    const sorted = [...buckets].sort((a, b) => b.items.length - a.items.length);
    return { sd: sorted[0]!.items, dx: sorted[1]!.items };
  }
  if (buckets.length === 1) {
    const items = buckets[0]!.items;
    return { sd: items.slice(0, Math.max(0, items.length - 15)), dx: items.slice(-15) };
  }
  return { sd: [], dx: [] };
}

/** 契约输入 → 内部绘制模型。 */
export function toB50Model(
  input: MaimaiB50RenderInput,
  songData: MaiSongData,
  extras: MaimaiB50RenderExtras = {},
): MaiB50Model {
  const { sd, dx } = pickBuckets(input);
  const sdRows = sd.map((score) => toRow(score, songData)).filter((row): row is MaiB50Row => row !== null);
  const dxRows = dx.map((score) => toRow(score, songData)).filter((row): row is MaiB50Row => row !== null);
  const sdTotal = sdRows.reduce((sum, row) => sum + row.rating, 0);
  const dxTotal = dxRows.reduce((sum, row) => sum + row.rating, 0);

  return {
    player: {
      name: input.profileName,
      rating: input.rating,
      courseRank: extras.courseRank ?? 0,
      classRank: extras.classRank ?? 0,
      trophy: extras.trophy ?? null,
    },
    sd: sdRows,
    dx: dxRows,
    sdTotal,
    dxTotal,
  };
}

/**
 * 移植实现的渲染器。
 *
 * 只负责 maimai；`renderPhigrosRks` 属于 Phigros 渲染器（render-phi 任务），
 * 这里显式抛错，避免误装配成一个「悄悄缺功能」的 Renderer。
 */
export class MaimaiRenderer implements Renderer {
  private readonly assets: MaiAssets;
  private readonly songData: MaiSongData;
  private readonly theme: MaiTheme;
  private readonly serviceLabel: string;
  private readonly botName: string;

  constructor(options: MaimaiRendererOptions = {}) {
    this.assets = new MaiAssets(options.assetsDir);
    this.songData = loadSongData(this.assets.dir);
    this.theme = options.theme ?? 'prism_plus';
    this.serviceLabel = options.serviceLabel ?? 'RankHub';
    this.botName = options.botName ?? 'RankHub';
  }

  /** 资源目录绝对路径（调用方/测试用来定位素材）。 */
  assetsDir(): string {
    return this.assets.dir;
  }

  async renderMaimaiB50(input: MaimaiB50RenderInput): Promise<Buffer> {
    const extras = input as MaimaiB50RenderInput & MaimaiB50RenderExtras;
    const model = toB50Model(input, this.songData, {
      courseRank: extras.courseRank,
      classRank: extras.classRank,
      trophy: extras.trophy ?? null,
    });
    return renderB50Png(model, {
      theme: extras.theme ?? this.theme,
      assets: this.assets,
      songData: this.songData,
      serviceLabel: this.serviceLabel,
      botName: this.botName,
    });
  }

  async renderPhigrosRks(): Promise<Buffer> {
    throw new Error(
      'MaimaiRenderer 不实现 Phigros 渲染；请使用 src/render/phi 的渲染器，或在装配层把两种渲染器组合成 Renderer。',
    );
  }

  async close(): Promise<void> {
    // @napi-rs/canvas 无需显式释放；保留接口供上层统一 close()。
  }
}

export function createMaimaiRenderer(options: MaimaiRendererOptions = {}): MaimaiRenderer {
  return new MaimaiRenderer(options);
}
